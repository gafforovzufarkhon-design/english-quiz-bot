def translate_text(text: str, target_lang: str = "tj") -> str:
    """
    Translate English text to Tajik or Russian.
    
    Args:
        text: English text to translate
        target_lang: 'tj' for Tajik, 'ru' for Russian
        
    Returns:
        Translated text or original text if no translation found
    """
    if not text:
        return ""
    
    # Convert to lowercase for matching
    text_lower = text.lower().strip()
    
    # Try to find exact match first
    if text_lower in TRANSLATION_DICT:
        return TRANSLATION_DICT[text_lower].get(target_lang, text)
    
    # Try word-by-word translation
    words = text_lower.split()
    translated_words = []
    
    for word in words:
        # Remove punctuation for matching
        clean_word = ''.join(c for c in word if c.isalnum())
        if clean_word in TRANSLATION_DICT:
            translated_words.append(TRANSLATION_DICT[clean_word].get(target_lang, word))
        else:
            translated_words.append(word)
    
    result = ' '.join(translated_words)
    
    # If we couldn't translate much, indicate that
    if result == text_lower:
        return None  # No translation available
    
    return result


def get_supported_languages() -> list:
    """Returns list of supported languages."""
    return ["tj", "ru"]


def get_translation_for_word(word: str, target_lang: str = "tj") -> tuple:
    """
    Get translation for an English word.
    
    Args:
        word: English word to translate
        target_lang: 'tj' for Tajik, 'ru' for Russian
        
    Returns:
        Tuple of (english_word, translation) or (None, None) if not found
    """
    word_lower = word.lower().strip()
    if word_lower in TRANSLATION_DICT:
        translation = TRANSLATION_DICT[word_lower].get(target_lang, word)
        return (word_lower, translation)
    return (None, None)


def get_random_word() -> str:
    """
    Get a random English word from the dictionary.
    
    Returns:
        A random English word
    """
    import random
    return random.choice(list(TRANSLATION_DICT.keys()))
