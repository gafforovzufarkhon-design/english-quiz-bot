def get_question_translation(level: int, question_index: int, language: str = "tj") -> str:
    """
    Get translation for a specific question.
    
    Args:
        level: The level number (1-100)
        question_index: The index of the question (0-9)
        language: 'tj' for Tajik, 'ru' for Russian
        
    Returns:
        The translated text or None if no translation available
    """
    translations_map = {
        1: LEVEL_1_TRANSLATIONS,
        2: LEVEL_2_TRANSLATIONS,
    }
    
    if level in translations_map:
        level_translations = translations_map[level]
        if question_index in level_translations:
            return level_translations[question_index].get(language)
    
    return None


